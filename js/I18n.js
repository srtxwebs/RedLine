const KEY = "site.lang";

function detect() {
  try {
    const saved = localStorage.getItem(KEY);
    if (saved === "en" || saved === "es") return saved;
  } catch {}
  return (navigator.language || "en").toLowerCase().startsWith("es") ? "es" : "en";
}

let lang = detect();

export const getLang = () => lang;
export const locale = () => (lang === "es" ? "es-MX" : "en-US");
export function hasExplicitLang() {
  try { return !!localStorage.getItem(KEY); } catch { return false; }
}

// t("key") → text in the current language. t("key", {name: "x"}) fills {name}.
export function t(key, vars = {}) {
  let v = DICT[lang][key] ?? DICT.en[key] ?? key;
  if (typeof v === "string") {
    const all = { brand: SITE.brand, year: new Date().getFullYear(), ...vars };
    v = v.replace(/\{(\w+)\}/g, (m, k) => (all[k] ?? m));
  }
  return v;
}

// Translates every element marked with data-i18n* attributes
export function applyTranslations(root = document) {
  root.querySelectorAll("[data-i18n]").forEach(el => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll("[data-i18n-html]").forEach(el => { el.innerHTML = t(el.dataset.i18nHtml); });
  root.querySelectorAll("[data-i18n-placeholder]").forEach(el => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  root.querySelectorAll("[data-i18n-aria]").forEach(el => { el.setAttribute("aria-label", t(el.dataset.i18nAria)); });
  root.querySelectorAll("[data-i18n-title]").forEach(el => { el.title = t(el.dataset.i18nTitle); });
  document.documentElement.lang = lang;
  const titleKey = document.body && document.body.dataset.title;
  if (titleKey) document.title = `${t(titleKey)} · ${SITE.brand}`;
  document.querySelectorAll("[data-lang]").forEach(b => {
    b.classList.toggle("active", b.dataset.lang === lang);
    b.setAttribute("aria-pressed", b.dataset.lang === lang ? "true" : "false");
  });
  document.documentElement.classList.add("i18n-ready");
}

export function setLang(next) {
  if ((next !== "en" && next !== "es") || next === lang) return;
  lang = next;
  try { localStorage.setItem(KEY, next); } catch {}
  applyTranslations();
  window.dispatchEvent(new CustomEvent("langchange", { detail: next }));
}

export const money = n =>
  new Intl.NumberFormat(locale(), { style: "currency", currency: SITE.currency, maximumFractionDigits: 0 }).format(n);

// "2026-10-17" → localized date text
export function fmtDay(ymd, opts = { weekday: "long", day: "numeric", month: "long", year: "numeric" }) {
  if (!ymd) return "";
  const [y, m, d] = ymd.split("-").map(Number);
  return new Intl.DateTimeFormat(locale(), opts).format(new Date(y, m - 1, d));
}

export function fmtDate(date, opts = { day: "numeric", month: "long", year: "numeric" }) {
  if (!date) return "";
  const d = typeof date.toDate === "function" ? date.toDate() : new Date(date);
  return new Intl.DateTimeFormat(locale(), opts).format(d);
}

export function fmtTime(hhmm) {
  const [h, m] = hhmm.split(":").map(Number);
  return new Intl.DateTimeFormat(locale(), { hour: "numeric", minute: "2-digit" }).format(new Date(2000, 0, 1, h, m));
}

